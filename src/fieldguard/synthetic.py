"""SYNTHETIC survey generator for tests, demos and benchmarks.

Everything produced here is artificial and labelled as such: every row carries a ``_synthetic`` column,
file names written by the CLI start with ``synthetic_``, and runs on this data are marked synthetic in
every report. It mimics a KoboToolbox CSV export of a household survey (group paths, ``_uuid``,
``_submission_time``, ``start``/``end`` with offsets, split GPS columns).

Honest enumerators get realistic heterogeneity (speed, DK propensity, working hours, rounding habits,
village differences). Fabricating enumerators ("curbstoners") apply a random subset of patterns to a
random share of their interviews, so detection is not trivial.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from typing import Any
from zoneinfo import ZoneInfo

import numpy as np
import pandas as pd

SYNTHETIC_LABEL = "SYNTHETIC - generated by fieldguard.synthetic (not real survey data)"

ALL_PATTERNS: tuple[str, ...] = (
    "short_duration",
    "straightlining",
    "low_variance",
    "benford",
    "heaping",
    "gps_clustering",
    "timing",
    "skip_shortcut",
    "low_dk",
    "near_duplicate",
)

WB_ITEMS = [f"wb/wb_{i}" for i in range(1, 9)]
WB_REVERSED = {"wb/wb_2", "wb/wb_5", "wb/wb_7"}
SVC_ITEMS = [f"svc/svc_{i}" for i in range(1, 7)]
WATER_SOURCES = ["piped", "borehole", "protected_well", "river", "vendor"]
AMOUNT_VARS = ["liv/monthly_income", "liv/business_income", "liv/livestock_value", "exp/food_exp", "exp/nonfood_exp"]


@dataclass
class SyntheticSpec:
    n_enumerators: int = 30
    interviews_per_enumerator: int = 25
    n_clusters: int = 15
    contamination: float = 0.15
    patterns: tuple[str, ...] = ALL_PATTERNS
    patterns_per_fabricator: tuple[int, int] = (2, 4)
    fabricated_share: tuple[float, float] = (0.6, 1.0)
    start_date: date = date(2025, 3, 3)
    timezone: str = "Africa/Nairobi"
    seed: int = 42

    def __post_init__(self) -> None:
        unknown = set(self.patterns) - set(ALL_PATTERNS)
        if unknown:
            raise ValueError(f"unknown fabrication patterns {sorted(unknown)}; choose from {ALL_PATTERNS}")
        if not 0 <= self.contamination < 1:
            raise ValueError("contamination must be in [0, 1)")
        if self.n_enumerators < 2:
            raise ValueError("need at least 2 enumerators")


@dataclass
class SyntheticSurvey:
    data: pd.DataFrame
    labels: pd.DataFrame
    truth: pd.DataFrame
    spec: SyntheticSpec
    notes: list[str] = field(default_factory=lambda: [SYNTHETIC_LABEL])


def _round_sig(x: float, sig: int) -> float:
    if x == 0 or not np.isfinite(x):
        return x
    return float(round(x, -int(np.floor(np.log10(abs(x)))) + (sig - 1)))


def _honest_amount(rng: np.random.Generator, mu: float, sd: float, rounding_pref: float) -> float:
    v = float(np.exp(rng.normal(mu, sd)))
    u = rng.random()
    if u < 0.15:
        return _round_sig(v, 1)
    if u < 0.15 + rounding_pref:
        return _round_sig(v, 2)
    return float(round(v, -1))


def _offset(lat: float, lon: float, d_north_m: float, d_east_m: float) -> tuple[float, float]:
    dlat = d_north_m / 111_320.0
    dlon = d_east_m / (111_320.0 * np.cos(np.radians(lat)))
    return lat + dlat, lon + dlon


def _uuid(rng: np.random.Generator) -> str:
    return str(uuid.UUID(int=int(rng.integers(0, 2**63)) << 64 | int(rng.integers(0, 2**63)), version=4))


def _workdays(start: date, n: int) -> list[date]:
    days, d = [], start
    while len(days) < n:
        if d.weekday() != 6:  # no Sundays
            days.append(d)
        d += timedelta(days=1)
    return days


def generate_survey(spec: SyntheticSpec | None = None) -> SyntheticSurvey:
    spec = spec or SyntheticSpec()
    rng = np.random.default_rng(spec.seed)
    tz = ZoneInfo(spec.timezone)
    n_enum = spec.n_enumerators
    n_fab = round(spec.contamination * n_enum)
    if spec.contamination > 0 and n_fab == 0:
        n_fab = 1
    enumerators = [f"E{i + 1:03d}" for i in range(n_enum)]
    fabricators = set(rng.choice(enumerators, size=n_fab, replace=False).tolist()) if n_fab else set()

    clusters = [f"V{i + 1:02d}" for i in range(spec.n_clusters)]
    centroids = {c: (-0.40 + rng.normal(0, 0.25), 36.95 + rng.normal(0, 0.25)) for c in clusters}
    village_wealth = {c: rng.normal(0, 0.35) for c in clusters}
    village_water = {c: rng.dirichlet(np.ones(len(WATER_SOURCES)) * 1.5) for c in clusters}
    perm = rng.permutation(n_enum)
    assignment = {
        e: [clusters[perm[i] % spec.n_clusters], clusters[(perm[i] + spec.n_clusters // 2 + 1) % spec.n_clusters]]
        for i, e in enumerate(enumerators)
    }
    days = _workdays(spec.start_date, 60)

    rows: list[dict[str, Any]] = []
    truth_rows: list[dict[str, Any]] = []
    label_rows: list[dict[str, Any]] = []
    hh_counter = dict.fromkeys(clusters, 0)
    record_no = 0

    for e in enumerators:
        is_fab = e in fabricators
        speed = float(np.exp(rng.normal(0, 0.15)))
        dk_prop = float(rng.uniform(0.005, 0.04))
        rounding_pref = float(rng.uniform(0.3, 0.6))
        day_start = float(rng.uniform(7.5, 9.5))
        per_day = int(rng.integers(3, 7))
        n_i = max(5, int(rng.poisson(spec.interviews_per_enumerator)))
        patterns: list[str] = []
        frac = 0.0
        if is_fab:
            lo, hi = spec.patterns_per_fabricator
            k = int(rng.integers(lo, hi + 1))
            k = max(1, min(k, len(spec.patterns)))
            patterns = sorted(rng.choice(list(spec.patterns), size=k, replace=False).tolist())
            frac = float(rng.uniform(*spec.fabricated_share))
        fabricated = rng.random(n_i) < frac if is_fab else np.zeros(n_i, dtype=bool)
        if is_fab and not fabricated.any():
            fabricated[rng.integers(0, n_i)] = True
        home_cluster = assignment[e][0]
        home = _offset(*centroids[home_cluster], rng.normal(0, 300), rng.normal(0, 300))
        lv_income = float(np.exp(rng.normal(9.6, 0.3)))
        prev_fab: dict[str, Any] | None = None
        prev_point: tuple[float, float] | None = None

        # schedule: honest interviews in daytime; fabricated with 'timing' in evening batches
        day_idx = int(rng.integers(0, 3))
        clock = datetime.combine(days[day_idx], datetime.min.time(), tz) + timedelta(hours=day_start)
        done_today = 0
        evening_clock: datetime | None = None
        for j in range(n_i):
            fab = bool(fabricated[j])
            cluster = assignment[e][j % 2] if rng.random() < 0.85 else assignment[e][0]
            w = rng.normal(village_wealth[cluster], 1.0)
            has_business = rng.random() < 0.35 + 0.1 * np.tanh(w)
            owns_land = rng.random() < 0.55
            base_d = (
                40 * speed * float(np.exp(rng.normal(0, 0.22))) + (6 if has_business else 0) + (4 if owns_land else 0)
            )
            if not fab and rng.random() < 0.02:
                base_d *= 0.45  # legitimate short (partial/quick) interview
            hh_counter[cluster] += 1
            rec: dict[str, Any] = {
                "enum_id": e,
                "village": cluster,
                "hhid": f"{cluster}-{hh_counter[cluster]:04d}",
                "consent": "yes",
                "resp/name": f"Synthetic Person {record_no + 1:05d}",
                "resp/phone": "07" + "".join(str(d) for d in rng.integers(0, 10, 8)),
                "resp/age": int(np.clip(round(rng.normal(41, 14)), 18, 92)),
                "resp/sex": "female" if rng.random() < 0.52 else "male",
            }
            if rng.random() < 0.15:
                rec["resp/age"] = int(5 * round(rec["resp/age"] / 5))
            hh_size = 1 + int(rng.poisson(4.2))
            rec["hh/hh_size"] = hh_size
            rec["hh/n_children"] = int(rng.binomial(max(hh_size - 1, 0), 0.45))
            rec["liv/has_business"] = "yes" if has_business else "no"
            rec["liv/business_income"] = (
                _honest_amount(rng, 9.0 + 0.5 * w, 0.9, rounding_pref) if has_business else None
            )
            rec["liv/monthly_income"] = _honest_amount(rng, 9.3 + 0.6 * w, 0.85, rounding_pref)
            rec["liv/livestock_value"] = (
                _honest_amount(rng, 10.0 + 0.8 * w, 1.0, rounding_pref) if rng.random() < 0.6 else 0.0
            )
            inc = rec["liv/monthly_income"]
            rec["exp/food_exp"] = _honest_amount(rng, np.log(inc * rng.uniform(0.25, 0.6)), 0.2, rounding_pref)
            rec["exp/nonfood_exp"] = _honest_amount(rng, np.log(inc * rng.uniform(0.1, 0.35)), 0.3, rounding_pref)
            rec["land/owns_land"] = "yes" if owns_land else "no"
            rec["land/land_size"] = round(float(np.exp(rng.normal(0.4, 0.7))), 1) if owns_land else None
            rec["water/water_source"] = str(rng.choice(WATER_SOURCES, p=village_water[cluster]))
            minutes = int(max(1, round(np.exp(rng.normal(np.log(15), 0.7)))))
            rec["water/minutes_to_water"] = int(5 * round(minutes / 5)) if rng.random() < 0.3 else minutes
            rec["assets/n_phones"] = int(rng.poisson(max(0.2, 1.2 + 0.4 * w)))
            theta, theta2 = rng.normal(0, 1), rng.normal(0, 1)
            for item in WB_ITEMS:
                sign = -1 if item in WB_REVERSED else 1
                rec[item] = int(np.clip(round(3 + 0.9 * sign * theta + rng.normal(0, 0.8)), 1, 5))
            for item in SVC_ITEMS:
                rec[item] = int(np.clip(round(3.2 + 0.8 * theta2 + rng.normal(0, 0.9)), 1, 5))
            # honest item nonresponse
            for var in (
                "liv/monthly_income",
                "liv/livestock_value",
                "land/land_size",
                "water/minutes_to_water",
                "exp/nonfood_exp",
            ):
                if rec.get(var) is not None and rng.random() < dk_prop:
                    rec[var] = -99
                elif var == "liv/monthly_income" and rng.random() < dk_prop / 3:
                    rec[var] = -98
            lat, lon = _offset(*centroids[cluster], rng.normal(0, 350), rng.normal(0, 350))
            acc = float(rng.uniform(3, 15)) if rng.random() > 0.05 else float(rng.uniform(30, 80))
            duration = base_d

            if fab:
                if "short_duration" in patterns:
                    duration = base_d * rng.uniform(0.25, 0.5)
                if "skip_shortcut" in patterns:
                    if rng.random() < 0.9:
                        rec["liv/has_business"], rec["liv/business_income"] = "no", None
                        duration -= 6 if has_business else 0
                    if rng.random() < 0.9:
                        rec["land/owns_land"], rec["land/land_size"] = "no", None
                if "low_variance" in patterns:
                    rec["hh/hh_size"] = int(rng.choice([4, 5]))
                    rec["hh/n_children"] = int(rng.choice([2, 3]))
                    rec["resp/age"] = int(round(rng.normal(38, 3)))
                    rec["liv/monthly_income"] = round(lv_income * (1 + rng.normal(0, 0.08)), -1)
                    rec["exp/food_exp"] = round(rec["liv/monthly_income"] * 0.45, -1)
                    rec["water/minutes_to_water"] = int(round(rng.normal(15, 2)))
                    rec["assets/n_phones"] = 1
                    for item in WB_ITEMS + SVC_ITEMS:
                        rec[item] = int(rng.choice([3, 4]))
                if "straightlining" in patterns:
                    for grid in (WB_ITEMS, SVC_ITEMS):
                        if rng.random() < 0.8:
                            v = int(rng.choice([3, 4, 4, 5]))
                            for item in grid:
                                rec[item] = v
                if "benford" in patterns:
                    rec["liv/monthly_income"] = float(round(rng.uniform(4000, 9500), -1))
                    rec["exp/food_exp"] = float(round(rng.uniform(2000, 4800), -1))
                    rec["exp/nonfood_exp"] = float(round(rng.uniform(600, 950), -1))
                    rec["liv/livestock_value"] = float(round(rng.uniform(30000, 90000), -2))
                    if rec.get("liv/business_income") is not None:
                        rec["liv/business_income"] = float(round(rng.uniform(5000, 9000), -1))
                if "heaping" in patterns:
                    for var in AMOUNT_VARS:
                        v = rec.get(var)
                        if v is not None and v > 0:
                            rec[var] = (
                                float(max(500, 500 * round(v / 500))) if v < 20000 else float(5000 * round(v / 5000))
                            )
                    rec["resp/age"] = (
                        int(10 * round(rec["resp/age"] / 10))
                        if rng.random() < 0.6
                        else int(5 * round(rec["resp/age"] / 5))
                    )
                    rec["water/minutes_to_water"] = int(max(10, 10 * round(rec["water/minutes_to_water"] / 10)))
                if "low_dk" in patterns:
                    for var in (
                        "liv/monthly_income",
                        "liv/livestock_value",
                        "land/land_size",
                        "water/minutes_to_water",
                        "exp/nonfood_exp",
                    ):
                        if rec.get(var) in (-99, -98):
                            rec[var] = 0.0 if var == "liv/livestock_value" else _honest_amount(rng, 8.0, 0.5, 0.5)
                if "near_duplicate" in patterns and prev_fab is not None and rng.random() < 0.5:
                    keep = {"enum_id", "village", "hhid", "resp/name", "resp/phone"}
                    for k2, v2 in prev_fab.items():
                        if k2 not in keep:
                            rec[k2] = v2
                    rec["resp/age"] = int(rec["resp/age"]) + int(rng.integers(-2, 3))
                if "gps_clustering" in patterns:
                    if prev_point is not None and rng.random() < 0.3:
                        lat, lon = prev_point
                    else:
                        lat, lon = _offset(*home, rng.normal(0, 4), rng.normal(0, 4))
                    acc = float(rng.uniform(3, 8))
                    prev_point = (lat, lon)
                prev_fab = dict(rec)

            # --- timestamps
            if fab and "timing" in patterns:
                if evening_clock is None or rng.random() < 0.25:
                    d = days[min(day_idx, len(days) - 1)]
                    evening_clock = datetime.combine(d, datetime.min.time(), tz) + timedelta(
                        hours=float(rng.uniform(19.5, 21.5))
                    )
                start = evening_clock
                end = start + timedelta(minutes=float(duration))
                evening_clock = end + timedelta(minutes=float(rng.uniform(-12, 2)))
            else:
                if done_today >= per_day:
                    day_idx += 1
                    done_today = 0
                    clock = datetime.combine(days[min(day_idx, len(days) - 1)], datetime.min.time(), tz) + timedelta(
                        hours=day_start + float(rng.normal(0, 0.3))
                    )
                start = clock
                end = start + timedelta(minutes=float(duration))
                clock = end + timedelta(minutes=float(rng.uniform(10, 40)))
                done_today += 1
            submitted = end + timedelta(hours=float(rng.uniform(0.2, 8)))
            record_no += 1
            rec.update(
                {
                    "start": start.isoformat(timespec="milliseconds"),
                    "end": end.isoformat(timespec="milliseconds"),
                    "today": start.date().isoformat(),
                    "deviceid": f"synthetic-device-{e}",
                    "gps": f"{lat:.6f} {lon:.6f} {rng.uniform(1500, 1700):.1f} {acc:.1f}",
                    "_gps_latitude": round(lat, 6),
                    "_gps_longitude": round(lon, 6),
                    "_gps_altitude": round(float(rng.uniform(1500, 1700)), 1),
                    "_gps_precision": round(acc, 1),
                    "_id": 100000 + record_no,
                    "_uuid": _uuid(rng),
                    "_submission_time": submitted.astimezone(ZoneInfo("UTC"))
                    .replace(tzinfo=None)
                    .isoformat(timespec="seconds"),
                    "_index": record_no,
                    "_synthetic": SYNTHETIC_LABEL,
                }
            )
            rows.append(rec)
            truth_rows.append({"_uuid": rec["_uuid"], "hhid": rec["hhid"], "enum_id": e, "is_fabricated": fab})
        label_rows.append(
            {
                "enumerator": e,
                "is_fabricator": is_fab,
                "patterns": ";".join(patterns),
                "fabricated_share": float(fabricated.mean()),
                "n_interviews": n_i,
                "n_fabricated": int(fabricated.sum()),
            }
        )

    order = [
        "start",
        "end",
        "today",
        "deviceid",
        "enum_id",
        "village",
        "hhid",
        "consent",
        "resp/name",
        "resp/phone",
        "resp/age",
        "resp/sex",
        "hh/hh_size",
        "hh/n_children",
        "liv/has_business",
        "liv/business_income",
        "liv/monthly_income",
        "liv/livestock_value",
        "exp/food_exp",
        "exp/nonfood_exp",
        "land/owns_land",
        "land/land_size",
        "water/water_source",
        "water/minutes_to_water",
        "assets/n_phones",
        *WB_ITEMS,
        *SVC_ITEMS,
        "gps",
        "_gps_latitude",
        "_gps_longitude",
        "_gps_altitude",
        "_gps_precision",
        "_id",
        "_uuid",
        "_submission_time",
        "_index",
        "_synthetic",
    ]
    df = pd.DataFrame(rows)[order]
    # export-like text frame: integers without '.0', missing as NaN
    text = df.astype("object").map(_fmt_cell)
    text = text.astype("str").mask(df.isna())
    return SyntheticSurvey(data=text, labels=pd.DataFrame(label_rows), truth=pd.DataFrame(truth_rows), spec=spec)


def _fmt_cell(v: Any) -> Any:
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return None
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


