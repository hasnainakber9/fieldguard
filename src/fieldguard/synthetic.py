def generate_backcheck(survey: SyntheticSurvey, hhids: list[str], seed: int = 7) -> pd.DataFrame:
    """Simulate back-check re-interviews for the given households (SYNTHETIC).

    Honest interviews mostly agree with the re-interview; fabricated ones disagree because the
    reported answers were invented.
    """
    rng = np.random.default_rng(seed)
    data = survey.data.set_index("hhid")
    fab = survey.truth.set_index("hhid")["is_fabricated"]
    rows = []
    for h in hhids:
        if h not in data.index:
            continue
        o = data.loc[h]
        if isinstance(o, pd.DataFrame):
            o = o.iloc[0]
        is_fab = bool(fab.get(h, False))

        def num(v: Any) -> float:
            try:
                return float(v)
            except (TypeError, ValueError):
                return float("nan")

        size = num(o["hh/hh_size"])
        if is_fab:
            true_size = 1 + int(rng.poisson(4.2))
            rec = {
                "hh_size": true_size,
                "water_source": str(rng.choice(WATER_SOURCES)),
                "owns_land": "yes" if rng.random() < 0.55 else "no",
                "n_children": int(rng.binomial(max(true_size - 1, 0), 0.45)),
                "minutes_to_water": int(max(1, round(np.exp(rng.normal(np.log(15), 0.7))))),
                "monthly_income": float(round(np.exp(rng.normal(9.3, 0.9)), -1)),
            }
        else:
            rec = {
                "hh_size": int(size + (rng.choice([-1, 1]) if rng.random() < 0.05 else 0))
                if np.isfinite(size)
                else None,
                "water_source": o["water/water_source"] if rng.random() < 0.95 else str(rng.choice(WATER_SOURCES)),
                "owns_land": o["land/owns_land"]
                if rng.random() < 0.95
                else ("no" if o["land/owns_land"] == "yes" else "yes"),
                "n_children": int(num(o["hh/n_children"]) + (rng.choice([-1, 1]) if rng.random() < 0.12 else 0)),
                "minutes_to_water": int(max(1, round(num(o["water/minutes_to_water"]) * np.exp(rng.normal(0, 0.25)))))
                if num(o["water/minutes_to_water"]) > 0
                else o["water/minutes_to_water"],
                "monthly_income": float(round(num(o["liv/monthly_income"]) * np.exp(rng.normal(0, 0.12)), -1))
                if num(o["liv/monthly_income"]) > 0
                else o["liv/monthly_income"],
            }
        rec = {"hhid": h, "bc_id": f"BC{int(rng.integers(1, 4))}", **rec, "_synthetic": SYNTHETIC_LABEL}
        rows.append(rec)
    out = pd.DataFrame(rows)
    return out.astype("object").map(_fmt_cell).astype("str").mask(out.isna())
